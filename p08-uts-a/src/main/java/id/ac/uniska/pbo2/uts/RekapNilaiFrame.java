    /**
     * Pengaturan yang tidak tersedia di jendela Properties:
     * model tabel, placeholder, warna pesan, dan tombol default (Enter = Simpan).
     */
    private void siapkanTampilan() {
        setLocationRelativeTo(null);
        getRootPane().setDefaultButton(simpanButton);

        // Hubungkan JTable dengan model tabel buatan sendiri.
        mahasiswaTabel.setModel(modelTabel);
        mahasiswaTabel.getColumnModel().getColumn(0).setPreferredWidth(110);
        mahasiswaTabel.getColumnModel().getColumn(1).setPreferredWidth(200);
        for (int kolom = 2; kolom <= 5; kolom++) {
           mahasiswaTabel.getColumnModel().getColumn(kolom).setPreferredWidth(70);
        }
        mahasiswaTabel.getColumnModel().getColumn(6).setPreferredWidth(60);

        // Kolom Akhir berisi teks (82,50) sehingga dibuat rata kanan secara manual.
        DefaultTableCellRenderer rataKanan = new DefaultTableCellRenderer();
        rataKanan.setHorizontalAlignment(SwingConstants.RIGHT);
        mahasiswaTabel.getColumnModel().getColumn(5).setCellRenderer(rataKanan);

        // Pesan kesalahan berwarna merah.
        pesanLabel.setForeground(new Color(204, 0, 0));

        // Placeholder (fitur FlatLaf).
        npmText.putClientProperty("JTextField.placeholderText", "10 digit angka");
        tugasText.putClientProperty("JTextField.placeholderText", "0 sampai 100");
        utsText.putClientProperty("JTextField.placeholderText", "0 sampai 100");
        uasText.putClientProperty("JTextField.placeholderText", "0 sampai 100");
    }

    /**
     * Memeriksa semua isian. Jika semuanya valid, data ditambahkan ke tabel.
     * Jika ada yang salah: data tidak disimpan, pesan tampil, kursor pindah
     * ke isian yang salah, dan isian lain tidak dihapus.
     */
    private void simpan() {
        hapusTandaError();

        String npm = npmText.getText().strip();
        String nama = namaText.getText().strip();

        if (!npm.matches("[0-9]{10}")) {
            tampilkanError("NPM harus 10 digit angka", npmText);
            return;
        }
        if (modelTabel.adaNpm(npm)) {
            tampilkanError("NPM " + npm + " sudah terdaftar", npmText);
            return;
        }
        if (nama.isEmpty()) {
            tampilkanError("Nama wajib diisi", namaText);
            return;
        }

        int tugas = bacaNilai(tugasText, "Nilai Tugas");
        if (tugas < 0) {
            return;
        }
        int uts = bacaNilai(utsText, "Nilai UTS");
        if (uts < 0) {
            return;
        }
        int uas = bacaNilai(uasText, "Nilai UAS");
        if (uas < 0) {
            return;
        }

        modelTabel.tambah(new NilaiMahasiswa(npm, nama, tugas, uts, uas));
        bersihkanForm();
        perbaruiRingkasan();

        // Gulung tabel ke baris terakhir.
        int barisTerakhir = modelTabel.getRowCount() - 1;
        mahasiswaTabel.scrollRectToVisible(mahasiswaTabel.getCellRect(barisTerakhir, 0, true));
    }

    /**
     * Membaca isian nilai. Mengembalikan angka 0 sampai 100,
     * atau -1 jika tidak valid (pesan kesalahan sudah ditampilkan).
     */
    private int bacaNilai(JTextField field, String namaNilai) {
        String teks = field.getText().strip();
        if (teks.matches("[0-9]{1,9}")) {
            int nilai = Integer.parseInt(teks);
            if (nilai <= 100) {
                return nilai;
            }
        }
        tampilkanError(namaNilai + " harus angka bulat 0 sampai 100", field);
        return -1;
    }

    private void tampilkanError(String pesan, JTextField fieldSalah) {
        pesanLabel.setText(pesan);
        fieldSalah.putClientProperty("JComponent.outline", "error");
        fieldSalah.requestFocusInWindow();
    }

    private void hapusTandaError() {
        pesanLabel.setText("");
        npmText.putClientProperty("JComponent.outline", null);
        namaText.putClientProperty("JComponent.outline", null);
        tugasText.putClientProperty("JComponent.outline", null);
        utsText.putClientProperty("JComponent.outline", null);
        uasText.putClientProperty("JComponent.outline", null);
    }

    /** Mengosongkan semua isian dan pesan kesalahan. */
    private void bersihkanForm() {
        npmText.setText("");
        namaText.setText("");
        tugasText.setText("");
        utsText.setText("");
        uasText.setText("");
        hapusTandaError();
        npmText.requestFocusInWindow();
    }

    private void perbaruiRingkasan() {
        ringkasanLabel.setText("Jumlah mahasiswa: " + modelTabel.getJumlah()
                + ", rata-rata nilai akhir: " + modelTabel.getRataRataAkhirTeks());
    }

